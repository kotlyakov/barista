import assert from 'node:assert/strict';
import * as model from './dist/game.mjs';
const {createGame,tap,finish,serve,advance,temperature,collectPayment,steamLevel,setTemperature,TAPS,PAYMENT_SECONDS}=model;
assert.equal(typeof collectPayment,'function','payment collection is exposed');
assert.equal(typeof steamLevel,'function','continuous steam is exposed');
assert.equal(typeof setTemperature,'function','temperature control is exposed');
const brew=(g,recipe)=>{g.active.recipe=recipe;for(const s of (recipe==='espresso'?[0,1]:[0,1,2]))for(let n=0;n<TAPS;n++)tap(g,s);return finish(g);};
const g=createGame();
assert.equal(tap(g,1).ok,false,'cannot brew before grinding');
const cap=brew(g,'cappuccino');
const esp=brew(g,'espresso');
assert.equal(g.cups.length,2,'can stockpile different drinks');
assert.equal(serve(g,esp.id,'beard').kind,'wrong','wrong drink is accepted but causes complaint');
assert.equal(g.cups.length,1);
assert.equal(serve(g,cap.id,'beard').ok,false,'cannot serve an already served customer');
assert.equal(g.cups.length,1,'rejected drop keeps cup');
advance(g,130);
assert.ok(temperature(cap)<50);
assert.equal(serve(g,cap.id,'hawaii').kind,'wrong-cold','cold wrong drink reports both');
const h=createGame();const fresh=brew(h,'cappuccino');
assert.deepEqual(collectPayment(h,'beard'),{ok:false,amount:0},'cannot collect before delivery');
assert.deepEqual(collectPayment(h,'missing'),{ok:false,amount:0},'unknown customer has no payment');
assert.equal(serve(h,fresh.id,'beard').kind,'happy');
assert.equal(h.money,0,'delivery leaves money uncollected');
assert.deepEqual(collectPayment(h,'beard'),{ok:true,amount:120});
assert.equal(h.money,120);
assert.deepEqual(collectPayment(h,'beard'),{ok:false,amount:0},'payment cannot be collected twice');
assert.equal(h.money,120);
assert.equal(serve(h,fresh.id,'hawaii').ok,false,'cup cannot be served twice');
const heat=brew(createGame(),'cappuccino');
assert.equal(temperature(heat),88);
assert.equal(steamLevel(heat),1);
setTemperature(heat,69);
assert.equal(temperature(heat),69);
assert.equal(steamLevel(heat),.5,'steam changes continuously with heat');
setTemperature(heat,49);
assert.equal(steamLevel(heat),0,'cold coffee has no steam');
setTemperature(heat,50);
assert.equal(steamLevel(heat),0);
setTemperature(heat,100);
assert.equal(temperature(heat),95);
assert.equal(steamLevel(heat),1);
heat.age=10;
assert.equal(temperature(heat),91.5,'manually heated drinks continue cooling');
setTemperature(heat,0);
assert.equal(temperature(heat),22);
assert.equal(steamLevel(heat),0);
assert.deepEqual(collectPayment(g,'beard'),{ok:false,amount:0},'unpaid guest has left after timeout');
const q=createGame();for(let n=0;n<TAPS;n++)tap(q,0);
const beforeExtra=q.active.quality;
for(let n=0;n<3;n++)tap(q,0);
assert.ok(q.active.quality<beforeExtra,'extra taps lower drink quality');for(let n=0;n<TAPS;n++)tap(q,1);for(let n=0;n<TAPS;n++)tap(q,2);
assert.equal(serve(q,finish(q).id,'beard').kind,'bitter','extra taps spoil taste');
console.log('PASS: operation order, batch preparation, wrong/cold delivery, returned cup, duplicate delivery, taste, temperature, steam, payment.');

const timeout=createGame(),cup=brew(timeout,'cappuccino');serve(timeout,cup.id,'beard');
advance(timeout,PAYMENT_SECONDS-.1);assert.equal(timeout.customers[0].departed,undefined);
advance(timeout,.1);assert.equal(timeout.customers[0].departed,true);assert.equal(timeout.customers[0].unpaid,true);
assert.deepEqual(collectPayment(timeout,'beard'),{ok:false,amount:0});assert.equal(timeout.money,0);
const paid=createGame(),drink=brew(paid,'cappuccino');serve(paid,drink.id,'beard');advance(paid,1);collectPayment(paid,'beard');advance(paid,30);assert.equal(paid.customers[0].unpaid,undefined);assert.equal(paid.money,120);
const edge=createGame(),edgeCup=brew(edge,'cappuccino');serve(edge,edgeCup.id,'beard');edge.clock=edge.customers[0].paymentDeadline;assert.equal(collectPayment(edge,'beard').ok,false);
assert.equal(TAPS,12);console.log('PASS: twelve taps, timeout boundary, unpaid departure, paid customer keeps revenue.');
const ordinary=createGame();for(let stage=0;stage<3;stage++){for(let i=0;i<TAPS;i++)tap(ordinary,stage);if(stage===0)tap(ordinary,stage);}assert.equal(serve(ordinary,finish(ordinary).id,'beard').kind,'ordinary');assert.equal(collectPayment(ordinary,'beard').amount,100);
